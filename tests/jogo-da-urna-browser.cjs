const {app,BrowserWindow}=require('electron');
const express=require('express');
const {createServer}=require('node:http');
const {Server}=require('socket.io');
const path=require('node:path');
const fs=require('node:fs');
const assert=require('node:assert/strict');
app.disableHardwareAcceleration();
let server,io;
app.whenReady().then(async()=>{
  const web=express();web.use(express.static(path.join(__dirname,'../public')));
  server=createServer(web);io=new Server(server);
  io.on('connection',socket=>socket.on('join-room',()=>socket.emit('room-joined',{room:'qa'})));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const win=new BrowserWindow({show:false,width:540,height:960,webPreferences:{offscreen:true,backgroundThrottling:false}});
  const errors=[];win.webContents.on('console-message',(_event,details)=>{if(details?.level==='error')errors.push(details.message);});
  const js=code=>win.webContents.executeJavaScript(code,true);
  const wait=async condition=>{const start=Date.now();while(!await js(condition)){if(Date.now()-start>15000)throw Error('Timeout: '+condition);await new Promise(r=>setTimeout(r,80));}};
  await win.loadURL(`http://127.0.0.1:${server.address().port}/games/jogo-da-urna/?id=qa&overlay=1&duration=30`);
  await wait('Boolean(document.querySelector(".participant"))');
  await js(`localStorage.clear();window.TikTokBridge._dispatch('gift',{giftName:'Galaxy',repeatCount:1,eventId:'one',user:{uniqueId:'maria',nickname:'Maria',profilePictureUrl:location.origin+'/games/duelo-2d/icones/galaxia.webp'}});void 0`);
  await wait('document.querySelector("#score-flavio").textContent==="5.000"');
  const spotlight=await js(`({visible:!document.querySelector('.participant').hidden,text:document.querySelector('.participant').textContent,photo:document.querySelector('.participant img').getAttribute('src')})`);
  assert.equal(spotlight.visible,true);assert.match(spotlight.text,/Maria enviou Galáxia: \+5\.000 votos/);assert.ok(spotlight.photo);
  const dir=path.join(__dirname,'../artifacts/jogo-da-urna');fs.mkdirSync(dir,{recursive:true});
  fs.writeFileSync(path.join(dir,'participante.png'),(await win.webContents.capturePage()).toPNG());
  await js(`window.TikTokBridge._dispatch('gift',{giftId:5655,repeatCount:25,eventId:'two',user:{uniqueId:'a',nickname:'Ana'}});void 0`);
  await win.reload();
  await wait('document.querySelector("#score-flavio").textContent==="5.000"');
  await wait('document.querySelector("#score-lula").textContent==="250"');
  await js(`const key='jogo-da-urna:v1:qa';let data=JSON.parse(localStorage.getItem(key));data.rounds.phase='open';data.rounds.remainingMs=9000;localStorage.setItem(key,JSON.stringify(data));void 0`);
  await win.reload();
  await wait('document.querySelector(".round-bar").classList.contains("final-seconds")');
  assert.match(await js('document.querySelector("#round-phase").textContent'),/ÚLTIMOS VOTOS/);
  await js(`window.confirm=()=>true;document.querySelector('#reset').click();void 0`);
  assert.equal(await js('document.querySelector("#score-flavio").textContent'),'0');
  const saved=await js(`JSON.parse(localStorage.getItem('jogo-da-urna:v1:qa'))`);
  assert.deepEqual(saved.scores,{lula:0,flavio:0});assert.deepEqual(saved.rounds.wins,{lula:0,flavio:0});assert.equal(saved.people.length,0);
  assert.deepEqual(errors,[]);
  console.log('Browser OK: foto, destaque, fila após reload, placar restaurado, suspense e nova sessão.');
  win.destroy();io.close();server.close();app.exit(0);
}).catch(error=>{console.error(error);app.exit(1);});
